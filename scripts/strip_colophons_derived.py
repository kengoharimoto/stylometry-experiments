#!/usr/bin/env python3
"""Strip chapter-colophon lines from the derived line-structured corpora.

The base corpora are regenerated from source with is_colophon_line() in the
shared filter (2026-08-16). Derived corpora (noreuse, complements, genre,
E1) were built from the pre-clean base; since all their build steps are
line-local, deleting colophon lines in place is equivalent to rebuilding
them from the cleaned base. Single-line (ByT5) unsandhied variants are NOT
handled here — they are regenerated by the ByT5 script, whose input filter
now drops colophons itself.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from process_epic_puranas_unsandhied_local import is_colophon_line  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DIRS = ['corpus/epic_puranas_noreuse',
        'corpus/epic_puranas_sandhied_noreuse',
        'corpus/complements_sandhied', 'corpus/complements_src',
        'corpus/genre_control_sandhied', 'corpus/genre_control_src',
        'corpus/e1_apparatus_sandhied', 'corpus/e1_apparatus_src']

total = 0
for d in DIRS:
    p = ROOT / d
    if not p.exists():
        print(f'{d}: MISSING')
        continue
    removed = files = 0
    for f in sorted(p.glob('*.txt')):
        lines = f.read_text(encoding='utf-8').splitlines()
        keep = [l for l in lines if not is_colophon_line(l)]
        if len(keep) != len(lines):
            f.write_text('\n'.join(keep) + ('\n' if keep else ''),
                         encoding='utf-8')
            removed += len(lines) - len(keep)
            files += 1
    total += removed
    print(f'{d}: -{removed} lines in {files} files')
print(f'total removed: {total}')
